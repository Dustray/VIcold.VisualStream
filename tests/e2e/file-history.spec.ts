import { expect, test } from '@playwright/test'
import { openWorkspace } from './workspace'
import { readFile } from 'node:fs/promises'

test('startup is empty and both file sections can collapse independently', async ({ page }) => {
  const resources: string[] = []
  page.on('request', request => resources.push(request.url()))
  await page.goto('/')
  const session = page.getByRole('region', { name: '当前会话', exact: true })
  const history = page.getByRole('region', { name: '历史文件', exact: true })
  await expect(history).toContainText('导入的文件会保存在本机')
  await expect(page.locator('.file-entry')).toHaveCount(0)
  await expect(page.locator('.device-section')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '播放重放', exact: true })).toBeDisabled()
  await expect(page.locator('.speed-value')).toHaveText('0.0001×')
  await expect(page.getByRole('checkbox', { name: '20s 演示' })).not.toBeChecked()
  await expect(page.getByText('内置真实样例', { exact: true })).toHaveCount(0)
  await expect(page.getByText('文件在浏览器内处理', { exact: true })).toHaveCount(0)
  await expect(page.locator('.sidebar-help')).toHaveCount(0)
  await page.screenshot({ path: '.local/screenshots/empty-workspace.png' })
  await session.getByRole('button', { name: /当前会话/ }).click()
  await expect(session.getByRole('button', { name: /当前会话/ })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#session-file-list')).toBeHidden()
  await expect(page.locator('#history-file-list')).toBeVisible()
  await history.getByRole('button', { name: /历史文件/ }).click()
  await expect(page.locator('#history-file-list')).toBeHidden()
  await session.getByRole('button', { name: /当前会话/ }).click()
  await expect(page.locator('#session-file-list')).toBeVisible()
  expect(resources.filter(url => /\/samples\/|\.perfetto-trace|\.wasm(?:$|\?)/.test(url))).toEqual([])
  await page.getByRole('button', { name: '快捷键与帮助', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '快捷键与帮助', exact: true })).toBeVisible()
})

test('session cards locate file tracks without changing checkbox selection or playback position', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openWorkspace(page, 'dual')
  const session = page.getByRole('region', { name: '当前会话', exact: true })
  const entries = session.locator('.file-entry')
  const files = session.getByRole('checkbox')
  const scroller = page.locator('.timeline-vertical-scroller')
  const time = page.locator('.time-hero').first()
  const initialTime = await time.innerText()
  const secondFileTop = 77 * 29
  await entries.nth(1).locator('.file-main').click()
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(secondFileTop)
  await expect(files.first()).toBeChecked()
  await expect(files.nth(1)).toBeChecked()
  await expect(page.locator('.device-section')).toHaveCount(2)
  await scroller.evaluate(element => { element.scrollTop += 200; element.dispatchEvent(new Event('scroll')) })
  await entries.nth(1).locator('.file-main').click()
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(secondFileTop)
  await entries.first().locator('.file-resource').click()
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(0)
  await page.getByRole('combobox', { name: '筛选计算卡', exact: true }).selectOption({ index: 1 })
  await expect(page.locator('.device-section')).toHaveCount(1)
  await entries.nth(1).locator('.file-main').click()
  await expect(page.locator('.device-section')).toHaveCount(2)
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(secondFileTop)
  await page.screenshot({ path: '.local/screenshots/session-card-navigation.png' })
  await scroller.evaluate(element => { element.scrollTop = 300; element.dispatchEvent(new Event('scroll')) })
  await files.nth(1).uncheck()
  await expect(page.locator('.device-section')).toHaveCount(1)
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(300)
  await entries.nth(1).locator('.file-main').click()
  await expect(page.locator('.toast')).toContainText('请先勾选该文件')
  await expect(files.nth(1)).not.toBeChecked()
  await expect(page.locator('.device-section')).toHaveCount(1)
  expect(await scroller.evaluate(element => element.scrollTop)).toBe(300)
  await files.nth(1).check()
  await expect(page.locator('.device-section')).toHaveCount(2)
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(300)
  await entries.first().locator('.file-main').focus()
  await page.keyboard.press('Enter')
  await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBe(0)
  await expect(time).toHaveText(initialTime)
  await expect(files.first()).toBeChecked()
  await expect(files.nth(1)).toBeChecked()
  expect(errors).toEqual([])
})

test('session checkboxes control all views and history restores files across reloads', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openWorkspace(page, 'all')
  const session = page.getByRole('region', { name: '当前会话', exact: true })
  const history = page.getByRole('region', { name: '历史文件', exact: true })
  const files = session.getByRole('checkbox')
  await expect(page.locator('.device-section')).toHaveCount(3)
  await expect(history.locator('.history-entry')).toHaveCount(3)
  const filename = await files.first().getAttribute('aria-label')
  await files.nth(1).uncheck()
  await expect(page.locator('.device-section')).toHaveCount(2)
  await expect(page.locator('.timeline-footer')).toContainText('154 条展示轨道')
  await files.nth(2).uncheck()
  await expect(page.locator('.device-section')).toHaveCount(1)
  await page.screenshot({ path: '.local/screenshots/session-file-selection.png' })
  await page.getByRole('button', { name: 'CU 利用率', exact: true }).click()
  const utilization = page.getByRole('region', { name: 'CU 利用率统计' })
  await expect(utilization.locator('tbody tr')).toHaveCount(76)
  await files.first().uncheck()
  await expect(utilization.locator('tbody tr')).toHaveCount(0)
  await expect(page.locator('.timeline-footer')).toContainText('0 条展示轨道')
  await expect(page.getByRole('button', { name: '播放重放', exact: true })).toBeDisabled()
  await history.getByRole('button', { name: `打开历史文件 ${filename}`, exact: true }).click()
  await expect(files.first()).toBeChecked()
  await expect(page.locator('.file-entry')).toHaveCount(3)
  await expect(utilization.locator('tbody tr')).toHaveCount(76)
  await session.getByRole('button', { name: '全选', exact: true }).click()
  await expect(utilization.locator('tbody tr')).toHaveCount(228)
  await session.getByRole('button', { name: /^移除 / }).first().click()
  await expect(page.locator('.file-entry')).toHaveCount(2)
  await expect(history.locator('.history-entry')).toHaveCount(3)
  await page.reload()
  await expect(history.locator('.history-entry')).toHaveCount(3)
  await expect(page.locator('.file-entry')).toHaveCount(0)
  await expect(page.locator('.device-section')).toHaveCount(0)
  await history.getByRole('button', { name: `打开历史文件 ${filename}`, exact: true }).click()
  await expect(page.locator('.file-entry')).toHaveCount(1)
  await expect(page.locator('.device-section')).toHaveCount(1)
  await expect(page.locator('.import-progress')).toHaveCount(0)
  await expect(files.first()).toBeChecked()
  await history.getByRole('button', { name: `从历史记录中移除 ${filename}`, exact: true }).click()
  await expect(history.locator('.history-entry')).toHaveCount(2)
  await expect(page.locator('.file-entry')).toHaveCount(1)
  await page.reload()
  await expect(history.locator('.history-entry')).toHaveCount(2)
  expect(errors).toEqual([])
})

test('projects reopen original files from history and restore explicit file selection', async ({ page }) => {
  await openWorkspace(page, 'dual')
  const session = page.getByRole('region', { name: '当前会话', exact: true })
  const files = session.getByRole('checkbox')
  await files.nth(1).uncheck()
  await page.getByRole('slider', { name: '重放速度' }).fill('1')
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const saved = await (await downloading).path()
  const project = JSON.parse(await readFile(saved!, 'utf8'))
  expect(project.sources).toHaveLength(2)
  expect(project.visibleSources).toHaveLength(1)
  expect(project.speed).toBe(0.00005)
  await page.reload()
  await expect(page.locator('.file-entry')).toHaveCount(0)
  await page.getByTestId('project-input').setInputFiles(saved!)
  await expect(page.locator('.toast')).toContainText('已恢复')
  await expect(page.locator('.file-entry')).toHaveCount(2)
  await expect(page.locator('.device-section')).toHaveCount(1)
  await expect(files.first()).toBeChecked()
  await expect(files.nth(1)).not.toBeChecked()
  await expect(page.locator('.speed-value')).toHaveText('0.00005×')
  await session.getByRole('button', { name: '清空选择', exact: true }).click()
  const emptyDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const emptyProject = await (await emptyDownload).path()
  expect(JSON.parse(await readFile(emptyProject!, 'utf8')).visibleSources).toEqual([])
  await session.getByRole('button', { name: '全选', exact: true }).click()
  await page.getByTestId('project-input').setInputFiles(emptyProject!)
  await expect(page.locator('.device-section')).toHaveCount(0)
  await expect(page.locator('.file-entry')).toHaveCount(2)
  await expect(page.getByRole('button', { name: '播放重放', exact: true })).toBeDisabled()
})
