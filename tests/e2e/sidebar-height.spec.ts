import { expect, test, type Page } from '@playwright/test'

async function dragPanels(page: Page, ratio: number): Promise<void> {
  const panels = (await page.locator('.sidebar-files').boundingBox())!
  const handle = (await page.getByRole('separator', { name: '调整当前会话与历史文件高度', exact: true }).boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2, panels.y + (panels.height - 8) * ratio + 4, { steps: 12 })
  await page.mouse.up()
}

test('file panels resize, preserve their ratio and give up space when collapsed', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const splitter = page.getByRole('separator', { name: '调整当前会话与历史文件高度', exact: true })
  const session = page.getByRole('region', { name: '当前会话', exact: true })
  const history = page.getByRole('region', { name: '历史文件', exact: true })
  await expect(splitter).toBeVisible()
  await dragPanels(page, 0.55)
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  const panels = (await page.locator('.sidebar-files').boundingBox())!
  expect((await session.boundingBox())!.height).toBeCloseTo((panels.height - 8) * 0.55, 0)
  expect((await history.boundingBox())!.height).toBeCloseTo((panels.height - 8) * 0.45, 0)
  expect((await history.boundingBox())!.y - (await session.boundingBox())!.y - (await session.boundingBox())!.height).toBeCloseTo(8, 0)
  await page.reload()
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  await splitter.focus()
  await page.keyboard.press('ArrowUp')
  await expect(splitter).toHaveAttribute('aria-valuenow', '50')
  await page.keyboard.press('ArrowDown')
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  await page.keyboard.press('Home')
  expect((await session.boundingBox())!.height).toBeCloseTo(92, 0)
  await page.keyboard.press('End')
  expect((await history.boundingBox())!.height).toBeCloseTo(72, 0)
  await dragPanels(page, 0.55)
  const expandedHeight = (await session.boundingBox())!.height
  await history.getByRole('button', { name: /历史文件/ }).click()
  await expect(splitter).toHaveCount(0)
  expect((await session.boundingBox())!.height).toBeGreaterThan(expandedHeight)
  await history.getByRole('button', { name: /历史文件/ }).click()
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  await session.getByRole('button', { name: /当前会话/ }).click()
  await expect(splitter).toHaveCount(0)
  expect((await history.boundingBox())!.height).toBeGreaterThan(expandedHeight)
  await session.getByRole('button', { name: /当前会话/ }).click()
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await dragPanels(page, 0.7)
  await page.getByRole('tab', { name: /会话 1/ }).click()
  await expect(splitter).toHaveAttribute('aria-valuenow', '55')
  await page.setViewportSize({ width: 1040, height: 640 })
  expect((await session.boundingBox())!.height).toBeGreaterThanOrEqual(92)
  expect((await history.boundingBox())!.height).toBeGreaterThanOrEqual(72)
  expect(await page.locator('.sidebar').evaluate(element => element.scrollHeight - element.clientHeight)).toBeLessThanOrEqual(1)
  const handle = (await splitter.boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 4)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 24)
  await expect(splitter).toHaveClass(/dragging/)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(splitter).not.toHaveClass(/dragging/)
  const stoppedRatio = await splitter.getAttribute('aria-valuenow')
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 100)
  await page.mouse.up()
  await expect(splitter).toHaveAttribute('aria-valuenow', stoppedRatio!)
  expect(await page.locator('body').evaluate(element => element.style.cursor)).toBe('')
  await splitter.dblclick()
  expect(await page.evaluate(() => localStorage.getItem('visualstream.fileSplitRatio'))).toBeNull()
  expect((await session.boundingBox())!.height).toBeGreaterThan((await history.boundingBox())!.height)
  await page.screenshot({ path: '.local/screenshots/sidebar-height.png' })
  expect(errors).toEqual([])
})
