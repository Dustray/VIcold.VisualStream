import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { ProjectSnapshot } from '../../src/core/types'
import { importTraces, openWorkspace } from './workspace'

async function saveProject(page: Page): Promise<{ path: string; snapshot: ProjectSnapshot }> {
  await expect(page.locator('.timeline-overlay')).toHaveAttribute('aria-busy', 'false')
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const path = await (await downloading).path()
  if (!path) throw new Error('Project was not saved')
  return { path, snapshot: JSON.parse(await readFile(path, 'utf8')) as ProjectSnapshot }
}

test('each session retains its files, replay state and sidebar while history is shared', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openWorkspace(page, 'dual')
  const tab = page.getByRole('tab', { selected: true })
  await tab.dblclick()
  await page.getByRole('textbox', { name: '会话名称', exact: true }).fill('双卡分析')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('tab', { selected: true })).toContainText('双卡分析')
  await page.getByRole('region', { name: '当前会话', exact: true }).getByRole('checkbox').nth(1).uncheck()
  const timeline = (await page.locator('.timeline-overlay').boundingBox())!
  await page.mouse.move(timeline.x + 300, timeline.y + 95)
  await page.mouse.down()
  await page.mouse.move(timeline.x + 550, timeline.y + 95, { steps: 8 })
  await page.mouse.up()
  await page.locator('.timeline-heading').getByRole('button', { name: '缩放到选区', exact: true }).click()
  await page.getByRole('button', { name: '添加时间书签', exact: true }).click()
  await page.getByRole('slider', { name: '重放速度', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: '重放信息', exact: true }).click()
  await page.getByRole('button', { name: '时间书签', exact: true }).click()
  await page.locator('.timeline-vertical-scroller').evaluate(element => { element.scrollTop = 580 })
  await expect.poll(() => page.locator('.timeline-vertical-scroller').evaluate(element => element.scrollTop)).toBe(580)
  await page.getByRole('textbox', { name: '搜索任务或事件', exact: true }).fill('matmul')
  const before = (await saveProject(page)).snapshot
  expect(before.selection).not.toBeNull()
  expect(before.bookmarks).toHaveLength(1)
  expect(before.speed).toBe(0.0005)
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.getByRole('tab', { selected: true })).toContainText('会话 2')
  await expect(page.locator('.file-entry')).toHaveCount(0)
  await expect(page.locator('.history-entry')).toHaveCount(2)
  await expect(page.getByRole('textbox', { name: '搜索任务或事件', exact: true })).toHaveValue('')
  await importTraces(page, 'single')
  await expect(page.locator('.history-entry')).toHaveCount(3)
  await page.getByRole('checkbox', { name: '20s 演示', exact: true }).check()
  await page.getByRole('button', { name: '播放重放', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停重放', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '最大化时间轴面板', exact: true }).click()
  await page.getByRole('tab', { name: /双卡分析/ }).click()
  await expect(page.getByRole('button', { name: '最大化时间轴面板', exact: true })).toBeVisible()
  await expect(page.locator('.file-entry')).toHaveCount(2)
  await expect(page.getByRole('region', { name: '当前会话', exact: true }).getByRole('checkbox').nth(1)).not.toBeChecked()
  await expect(page.getByRole('textbox', { name: '搜索任务或事件', exact: true })).toHaveValue('matmul')
  await expect(page.getByRole('checkbox', { name: '20s 演示', exact: true })).not.toBeChecked()
  await expect(page.getByRole('button', { name: '重放信息', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('button', { name: '时间书签', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(() => page.locator('.timeline-vertical-scroller').evaluate(element => element.scrollTop)).toBe(580)
  expect((await saveProject(page)).snapshot).toEqual(before)
  await page.getByRole('tab', { name: /会话 2/ }).click()
  await expect(page.getByRole('button', { name: '播放重放', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: '20s 演示', exact: true })).toBeChecked()
  await expect(page.getByRole('slider', { name: '重放速度', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '还原时间轴面板', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '还原时间轴面板', exact: true }).click()
  await page.screenshot({ path: '.local/screenshots/multi-session-replay.png' })
  await page.getByRole('button', { name: '关闭会话 双卡分析', exact: true }).click()
  await expect(page.getByRole('tab')).toHaveCount(1)
  await expect(page.locator('.file-entry')).toHaveCount(1)
  expect(errors).toEqual([])
})

test('opening a project creates its own tab and closing it keeps the original replay usable', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await openWorkspace(page)
  await page.getByRole('button', { name: '添加时间书签', exact: true }).click()
  const saved = await saveProject(page)
  await page.getByTestId('project-input').setInputFiles(saved.path)
  await expect(page.getByRole('tab')).toHaveCount(2)
  await expect(page.locator('.file-entry')).toHaveCount(1)
  await expect(page.locator('.import-progress')).toHaveCount(0)
  expect((await saveProject(page)).snapshot).toEqual(saved.snapshot)
  const original = page.getByRole('tab', { name: /会话 1/ })
  await original.click()
  await page.getByRole('button', { name: '添加时间书签', exact: true }).click()
  expect((await saveProject(page)).snapshot.bookmarks).toHaveLength(2)
  await page.getByRole('tab').nth(1).click()
  expect((await saveProject(page)).snapshot.bookmarks).toHaveLength(1)
  await page.locator('.session-tab-entry.active .session-tab-close').click()
  await expect(page.getByRole('tab')).toHaveCount(1)
  await expect(page.locator('.file-entry')).toHaveCount(1)
  await page.getByRole('button', { name: '播放重放', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停重放', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '暂停重放', exact: true }).click()
  expect(errors).toEqual([])
})

test('tabs support keyboard navigation, renaming, overflow and closing the last session', async ({ page }) => {
  await page.goto('/')
  await page.setViewportSize({ width: 1040, height: 640 })
  for (let index = 0; index < 9; index++) await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.getByRole('tab')).toHaveCount(10)
  await expect(page.getByRole('button', { name: '新建会话', exact: true })).toBeInViewport()
  await expect(page.getByRole('textbox', { name: '搜索任务或事件', exact: true })).toBeInViewport()
  await page.getByRole('tab', { selected: true }).focus()
  await page.keyboard.press('Home')
  await expect(page.getByRole('tab', { selected: true })).toHaveText('会话 1')
  await expect(page.getByRole('tab', { selected: true })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { selected: true })).toHaveText('会话 2')
  await page.keyboard.press('F2')
  const name = page.getByRole('textbox', { name: '会话名称', exact: true })
  await name.fill('键盘会话')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('tab', { selected: true })).toHaveText('键盘会话')
  await page.keyboard.press('Delete')
  await expect(page.getByRole('tab')).toHaveCount(9)
  await page.getByRole('tab').first().click({ button: 'middle' })
  await expect(page.getByRole('tab')).toHaveCount(8)
  while (await page.getByRole('tab').count() > 1) await page.locator('.session-tab-entry.active .session-tab-close').click()
  await page.locator('.session-tab-entry.active .session-tab-close').click()
  await expect(page.getByRole('tab')).toHaveCount(1)
  await expect(page.locator('.file-entry')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '播放重放', exact: true })).toBeDisabled()
})
